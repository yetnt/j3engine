    @NotNull
    private List<int[]> findCuspDiagonals(@NotNull List<CartesianPoint> pts) {
        int n = pts.size();
        List<int[]> diagonals = new ArrayList<>();

        for (int i = 0; i < n; i++) {
            VertexType type = classifyVertex(pts, i);
            if (type == VertexType.SPLIT) {
                int bestJ = -1;
                double minDiff = Double.MAX_VALUE;
                for (int j = 0; j < n; j++) {
                    if (j == i) continue;
                    if (yPrime(pts.get(j)) > yPrime(pts.get(i))) {
                        double diff = yPrime(pts.get(j)) - yPrime(pts.get(i));
                        if (diff < minDiff && isValidDiagonal(pts, i, j)) {
                            minDiff = diff;
                            bestJ = j;
                        }
                    }
                }
                if (bestJ != -1) {
                    diagonals.add(new int[]{i, bestJ});
                }
            } else if (type == VertexType.MERGE) {
                int bestJ = -1;
                double minDiff = Double.MAX_VALUE;
                for (int j = 0; j < n; j++) {
                    if (j == i) continue;
                    if (yPrime(pts.get(j)) < yPrime(pts.get(i))) {
                        double diff = yPrime(pts.get(i)) - yPrime(pts.get(j));
                        if (diff < minDiff && isValidDiagonal(pts, i, j)) {
                            minDiff = diff;
                            bestJ = j;
                        }
                    }
                }
                if (bestJ != -1) {
                    diagonals.add(new int[]{i, bestJ});
                }
            }
        }

        return diagonals;
    }

    private VertexType classifyVertex(@NotNull List<CartesianPoint> pts, int i) {
        int n = pts.size();
        int prev = (i - 1 + n) % n;
        int next = (i + 1) % n;

        CartesianPoint pPrev = pts.get(prev);
        CartesianPoint pCurr = pts.get(i);
        CartesianPoint pNext = pts.get(next);

        boolean prevBelow = yPrime(pPrev) < yPrime(pCurr);
        boolean nextBelow = yPrime(pNext) < yPrime(pCurr);
        double turn = orient2d(pPrev, pCurr, pNext);

        if (prevBelow && nextBelow) {
            return turn > 0 ? VertexType.START : VertexType.SPLIT;
        } else if (!prevBelow && !nextBelow) {
            return turn > 0 ? VertexType.END : VertexType.MERGE;
        } else {
            return VertexType.REGULAR;
        }
    }

    private boolean isValidDiagonal(@NotNull List<CartesianPoint> pts, int i, int j) {
        int n = pts.size();
        if (i == j || (i + 1) % n == j || (j + 1) % n == i) {
            return false;
        }

        CartesianPoint pi = pts.get(i);
        CartesianPoint pj = pts.get(j);

        // Check if ray from i to j points into the polygon interior
        if (!isInteriorRay(pts, i, j) || !isInteriorRay(pts, j, i)) {
            return false;
        }

        // Check strict segment intersection with all boundary edges
        for (int k = 0; k < n; k++) {
            int nextK = (k + 1) % n;
            if (k == i || nextK == i || k == j || nextK == j) continue;
            if (segmentsStrictlyIntersect(pi, pj, pts.get(k), pts.get(nextK))) {
                return false;
            }
        }

        // Midpoint of diagonal must be inside the polygon
        CartesianPoint mid = new CartesianPoint((pi.x + pj.x) * 0.5, (pi.y + pj.y) * 0.5);
        return isPointInPolygon(mid, pts);
    }

    private boolean isInteriorRay(@NotNull List<CartesianPoint> pts, int i, int j) {
        int n = pts.size();
        CartesianPoint prev = pts.get((i - 1 + n) % n);
        CartesianPoint curr = pts.get(i);
        CartesianPoint next = pts.get((i + 1) % n);
        CartesianPoint target = pts.get(j);

        double turn = orient2d(prev, curr, next);
        if (turn >= 0) {
            return orient2d(curr, next, target) >= 0 && orient2d(curr, target, prev) >= 0;
        } else {
            return !(orient2d(curr, prev, target) >= 0 && orient2d(curr, target, next) >= 0);
        }
    }

    @NotNull
    private List<List<CartesianPoint>> partitionByDiagonals(List<CartesianPoint> original, @NotNull List<int[]> diagonals) {
        List<List<CartesianPoint>> polygons = new ArrayList<>();
        polygons.add(new ArrayList<>(original));

        for (int[] diag : diagonals) {
            CartesianPoint pA = original.get(diag[0]);
            CartesianPoint pB = original.get(diag[1]);

            int targetPolyIndex = -1;
            int idxA = -1;
            int idxB = -1;

            for (int p = 0; p < polygons.size(); p++) {
                List<CartesianPoint> poly = polygons.get(p);
                int posA = poly.indexOf(pA);
                int posB = poly.indexOf(pB);
                if (posA != -1 && posB != -1) {
                    int diff = Math.abs(posA - posB);
                    if (diff > 1 && diff < poly.size() - 1) {
                        targetPolyIndex = p;
                        idxA = posA;
                        idxB = posB;
                        break;
                    }
                }
            }

            if (targetPolyIndex != -1) {
                List<CartesianPoint> poly = polygons.remove(targetPolyIndex);
                if (idxA > idxB) {
                    int tmp = idxA;
                    idxA = idxB;
                    idxB = tmp;
                }

                List<CartesianPoint> p1 = new ArrayList<>();
                for (int i = idxA; i <= idxB; i++) {
                    p1.add(poly.get(i));
                }

                List<CartesianPoint> p2 = new ArrayList<>();
                for (int i = idxB; i < poly.size(); i++) {
                    p2.add(poly.get(i));
                }
                for (int i = 0; i <= idxA; i++) {
                    p2.add(poly.get(i));
                }

                polygons.add(p1);
                polygons.add(p2);
            }
        }

        return polygons;
    }

    @NotNull
    private List<CartesianPoint[]> triangulateMonotone(@NotNull List<CartesianPoint> poly) {
        int m = poly.size();
        List<CartesianPoint[]> triangles = new ArrayList<>();
        if (m < 3) return triangles;

        // Find top and bottom vertices
        int topIdx = 0;
        int botIdx = 0;
        for (int i = 1; i < m; i++) {
            if (yPrime(poly.get(i)) > yPrime(poly.get(topIdx))) {
                topIdx = i;
            }
            if (yPrime(poly.get(i)) < yPrime(poly.get(botIdx))) {
                botIdx = i;
            }
        }

        // Trace Left and Right chains
        Chain[] chains = new Chain[m];
        int curr = topIdx;
        while (curr != botIdx) {
            chains[curr] = Chain.LEFT;
            curr = (curr + 1) % m;
        }
        chains[botIdx] = Chain.LEFT;

        curr = (topIdx - 1 + m) % m;
        while (curr != botIdx) {
            chains[curr] = Chain.RIGHT;
            curr = (curr - 1 + m) % m;
        }

        List<SortedVertex> sorted = new ArrayList<>(m);
        for (int i = 0; i < m; i++) {
            sorted.add(new SortedVertex(i, poly.get(i), chains[i]));
        }
        sorted.sort((v1, v2) -> Double.compare(yPrime(v2.point()), yPrime(v1.point())));

        Deque<Integer> stack = new ArrayDeque<>();
        stack.push(0);
        stack.push(1);

        for (int j = 2; j < m - 1; j++) {
            SortedVertex uj = sorted.get(j);
            SortedVertex top = sorted.get(stack.peek());

            if (uj.chain() != top.chain()) {
                int lastPopped = stack.pop();
                while (!stack.isEmpty()) {
                    int v = stack.pop();
                    triangles.add(new CartesianPoint[]{uj.point(), sorted.get(lastPopped).point(), sorted.get(v).point()});
                    lastPopped = v;
                }
                stack.push(j - 1);
                stack.push(j);
            } else {
                int lastPopped = stack.pop();
                while (!stack.isEmpty()) {
                    int v = stack.peek();
                    CartesianPoint pv = sorted.get(v).point();
                    CartesianPoint pLast = sorted.get(lastPopped).point();
                    CartesianPoint pj = uj.point();

                    double turn = orient2d(pj, pLast, pv);
                    boolean isConvex = (uj.chain() == Chain.LEFT) ? (turn > 1e-9) : (turn < -1e-9);

                    if (isConvex) {
                        triangles.add(new CartesianPoint[]{pj, pLast, pv});
                        lastPopped = stack.pop();
                    } else {
                        break;
                    }
                }
                stack.push(lastPopped);
                stack.push(j);
            }
        }

        // Connect the last (bottom) vertex to all remaining vertices on the stack
        SortedVertex um = sorted.get(m - 1);
        int lastPopped = stack.pop();
        while (!stack.isEmpty()) {
            int v = stack.pop();
            triangles.add(new CartesianPoint[]{um.point(), sorted.get(lastPopped).point(), sorted.get(v).point()});
            lastPopped = v;
        }

        return triangles;
    }

    @NotNull
    private List<CartesianPoint[]> earClip2D(List<CartesianPoint> points) {
        List<CartesianPoint[]> tris = new ArrayList<>();
        ArrayList<CartesianPoint> working = new ArrayList<>(points);

        while (working.size() > 3) {
            boolean earFound = false;
            for (int i = 0; i < working.size(); i++) {
                int prev = (i - 1 + working.size()) % working.size();
                int next = (i + 1) % working.size();

                CartesianPoint pPrev = working.get(prev);
                CartesianPoint pCurr = working.get(i);
                CartesianPoint pNext = working.get(next);

                if (orient2d(pPrev, pCurr, pNext) <= 1e-9) continue;

                boolean isClean = true;
                for (int j = 0; j < working.size(); j++) {
                    if (j == prev || j == i || j == next) continue;
                    if (isPointInTriangle(working.get(j), pPrev, pCurr, pNext)) {
                        isClean = false;
                        break;
                    }
                }

                if (isClean) {
                    tris.add(new CartesianPoint[]{pPrev, pCurr, pNext});
                    working.remove(i);
                    earFound = true;
                    break;
                }
            }
            if (!earFound) break;
        }

        if (working.size() == 3) {
            tris.add(new CartesianPoint[]{working.get(0), working.get(1), working.get(2)});
        }

        return tris;
    }

    private void emitTriangle(List<Tri> tris, CartesianPoint a, CartesianPoint b, CartesianPoint c, boolean targetCCW, Map<UUID, GPoint> lookup) {
        double orient = orient2d(a, b, c);
        if (Math.abs(orient) < 1e-12) return;

        GPoint ga = lookup.get(a.getId());
        GPoint gb = lookup.get(b.getId());
        GPoint gc = lookup.get(c.getId());

        if (ga == null || gb == null || gc == null) return;

        if ((orient > 0) != targetCCW) {
            tris.add(new Tri(ga, gc, gb));
        } else {
            tris.add(new Tri(ga, gb, gc));
        }
    }

    @Contract(pure = true)
    private double yPrime(@NotNull CartesianPoint p) {
        return p.y + 1e-7 * p.x;
    }

    private double signedArea(@NotNull List<CartesianPoint> pts) {
        double sum = 0.0;
        int n = pts.size();
        for (int i = 0; i < n; i++) {
            CartesianPoint curr = pts.get(i);
            CartesianPoint next = pts.get((i + 1) % n);
            sum += (curr.x * next.y - next.x * curr.y);
        }
        return sum * 0.5;
    }

    @Contract(pure = true)
    private double orient2d(@NotNull CartesianPoint a, @NotNull CartesianPoint b, @NotNull CartesianPoint c) {
        return (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
    }

    private boolean segmentsStrictlyIntersect(CartesianPoint a, CartesianPoint b, CartesianPoint c, CartesianPoint d) {
        double d1 = orient2d(c, d, a);
        double d2 = orient2d(c, d, b);
        double d3 = orient2d(a, b, c);
        double d4 = orient2d(a, b, d);

        return ((d1 > 1e-9 && d2 < -1e-9) || (d1 < -1e-9 && d2 > 1e-9)) &&
               ((d3 > 1e-9 && d4 < -1e-9) || (d3 < -1e-9 && d4 > 1e-9));
    }

    private boolean isPointInPolygon(CartesianPoint p, @NotNull List<CartesianPoint> poly) {
        int n = poly.size();
        boolean inside = false;
        for (int i = 0, j = n - 1; i < n; j = i++) {
            CartesianPoint pi = poly.get(i);
            CartesianPoint pj = poly.get(j);
            if (((pi.y > p.y) != (pj.y > p.y)) &&
                    (p.x < (pj.x - pi.x) * (p.y - pi.y) / (pj.y - pi.y) + pi.x)) {
                inside = !inside;
            }
        }
        return inside;
    }

    @Contract(pure = true)
    private boolean isPointInTriangle(@NotNull CartesianPoint p, @NotNull CartesianPoint a, @NotNull CartesianPoint b, @NotNull CartesianPoint c) {
        double v0x = c.x - a.x, v0y = c.y - a.y;
        double v1x = b.x - a.x, v1y = b.y - a.y;
        double v2x = p.x - a.x, v2y = p.y - a.y;

        double dot00 = v0x * v0x + v0y * v0y;
        double dot01 = v0x * v1x + v0y * v1y;
        double dot02 = v0x * v2x + v0y * v2y;
        double dot11 = v1x * v1x + v1y * v1y;
        double dot12 = v1x * v2x + v1y * v2y;

        double denom = dot00 * dot11 - dot01 * dot01;
        if (Math.abs(denom) < 1e-12) return false;

        double invDenom = 1.0 / denom;
        double u = (dot11 * dot02 - dot01 * dot12) * invDenom;
        double v = (dot00 * dot12 - dot01 * dot02) * invDenom;

        return (u >= 0) && (v >= 0) && (u + v <= 1);
    }
