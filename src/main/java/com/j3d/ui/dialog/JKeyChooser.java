    enum Modifiers {
        CTRL(InputEvent.CTRL_DOWN_MASK, "Ctrl"),
        SHIFT(InputEvent.SHIFT_DOWN_MASK, "Shift"),
        ALT(InputEvent.ALT_DOWN_MASK, "Alt"),
        ALT_GRAPH(InputEvent.ALT_GRAPH_DOWN_MASK, "Alt Gr"),
        META(InputEvent.META_DOWN_MASK, "Meta");

        private final int mask;
        private final String name;
        Modifiers(int mask, String name) {
            this.mask = mask;
            this.name = name;
        }

        public static EnumSet<Modifiers> fromKeyStroke(int modifiers) {
            EnumSet<Modifiers> ret = EnumSet.noneOf(Modifiers.class);

            for (Modifiers m : Modifiers.values()) {
                if ((modifiers & m.mask) != 0) {
                    ret.add(m);
                }
            }
            return ret;
        }

        public static int toMask(EnumSet<Modifiers> mods) {
            int mask = 0;
            for (Modifiers m : mods) {
                mask |= m.mask;
            }
            return mask;
        }
    }

    EnumSet<Modifiers> modifiers = EnumSet.of(Modifiers.CTRL);
    int keyCode = KeyEvent.VK_A; // default
    HashMap<Modifiers, JCheckBox> checkboxes = new HashMap<>();
    KeyStroke finalKeyStroke;

