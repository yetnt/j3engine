    public JKeyChooser(JFrame parent, KeyStroke existingKeyStroke) {
        super(parent, true);
        initComponents();
        modifiers = Modifiers.fromKeyStroke(existingKeyStroke.getModifiers());
        keyCode = existingKeyStroke.getKeyCode();
        shortcuts();
        setInputField();
        setModifiersCheckboxes();
        shortcutTextFieldInputHandling();
        this.setVisible(true);
    }

    private void shortcuts() {
        checkboxes.put(Modifiers.CTRL, ctrlCheckBox);
        checkboxes.put(Modifiers.SHIFT, shiftCheckBox);
        checkboxes.put(Modifiers.ALT, altCheckBox);
        checkboxes.put(Modifiers.ALT_GRAPH, altGraphCheckBox);
        checkboxes.put(Modifiers.META, metaCheckBox);
    }

    private void setModifiersCheckboxes() {
        for (Map.Entry<Modifiers, JCheckBox> entry : checkboxes.entrySet()) {
            if (modifiers.contains(entry.getKey()))
                entry.getValue().setSelected(true);
            else
                entry.getValue().setSelected(false);
        }
    }

    private void setInputField() {
        String mods = modifiers
                .stream()
                .reduce("",
                        (m1, m2) -> {
                            return m1 + (m1.isBlank() ? "" : "+") + m2.name;
                        },
                        (s, e) -> {
                            return s + e;
                        }
                        );
        String key = getKeyText();

        shortcutTextField.setText(mods + " " + key);
    }

    private String getKeyText() {
        String t = KeyEvent.getKeyText(keyCode);
        if (!List.of("Shift", "Ctrl", "Alt", "Meta").contains(t))
            return t;
        return "";
    }

    private void shortcutTextFieldInputHandling() {
        shortcutTextField.setEditable(false);
        shortcutTextField.addKeyListener(new KeyAdapter() {
            @Override
            public void keyPressed(KeyEvent e) {
                modifiers = Modifiers.fromKeyStroke(e.getModifiersEx());
                keyCode = e.getKeyCode();
                setModifiersCheckboxes();
                setInputField();
            }
        });
    }

